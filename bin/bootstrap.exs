#!/usr/bin/env elixir
#
# bootstrap.exs — rename this boilerplate ("SampleProject" / :sample_project) into
# your own project. One-shot: run it once, review the diff, then delete it.
#
#   elixir bin/bootstrap.exs my_app            # interactive (confirm/override each form)
#   elixir bin/bootstrap.exs my_app --yes      # non-interactive (accept derived defaults)
#   elixir bin/bootstrap.exs my_app --dry-run  # preview only, write nothing
#   elixir bin/bootstrap.exs --help
#
# Pure Elixir on purpose: no sed/find/grep/perl, so it behaves identically on macOS
# and Linux and needs no CLI tools beyond Elixir itself (which you already have).

defmodule Bootstrap do
  # --- Source tokens (what this boilerplate is currently named) ------------------
  @old_module "SampleProject"
  @old_otp "sample_project"
  @old_joined "sampleproject"
  @old_kebab "sample-project"
  @old_title "Sample Project"

  # Directories never traversed: VCS, build output, fetched deps, editor/tooling
  # caches, and the content-hashed asset bundles (regenerated by `vite build`).
  @excluded_dirs ~w(.git _build deps node_modules .elixir_ls .hex-docs priv/static/assets)

  @self_path "bin/bootstrap.exs"
  @readme "README.md"

  def main(argv) do
    {opts, positional} = parse_args(argv)

    if opts[:help], do: print_help_and_halt()

    preflight!()

    names = resolve_names(positional, opts)
    names = confirm_names!(names, opts)

    files = collect_text_files()
    edits = plan_content_edits(files, names)
    moves = plan_path_moves(names)

    if opts[:dry_run] do
      report_dry_run(edits, moves)
      System.halt(0)
    end

    apply_edits(edits)
    write_readme(names)
    apply_moves(moves)

    report_done(edits, moves, names)
  end

  # --- Argument parsing ----------------------------------------------------------

  defp parse_args(argv) do
    {parsed, rest, invalid} =
      OptionParser.parse(argv,
        strict: [
          module: :string,
          otp: :string,
          joined: :string,
          kebab: :string,
          title: :string,
          dry_run: :boolean,
          yes: :boolean,
          help: :boolean
        ]
      )

    unless invalid == [] do
      bad = invalid |> Enum.map_join(", ", fn {flag, _} -> flag end)
      abort("unknown option(s): #{bad}\nRun with --help to see usage.")
    end

    # OptionParser omits flags that weren't passed, so boolean options come back as
    # nil. Default them to false up front — Elixir's `or`/`and` are strict and would
    # raise BadBooleanError on a nil operand (e.g. `opts[:yes] or opts[:dry_run]`).
    opts = Keyword.merge([yes: false, dry_run: false, help: false], parsed)

    {opts, rest}
  end

  # --- Preflight guards ----------------------------------------------------------

  defp preflight!() do
    unless File.regular?("mix.exs") do
      abort("mix.exs not found — run this from the project root.")
    end

    unless File.read!("mix.exs") =~ ":#{@old_otp}" do
      abort(
        "mix.exs does not reference :#{@old_otp}.\n" <>
          "This project may already be bootstrapped (or this isn't the boilerplate)."
      )
    end

    if File.dir?(".git") do
      info("Tip: commit or stash first so you can review (and undo) the rename via git.\n")
    end
  end

  # --- Name resolution + derivation ---------------------------------------------

  defp resolve_names(positional, opts) do
    base =
      case positional do
        [name | _] -> name
        [] -> prompt_required_name(opts)
      end
      |> String.trim()

    validate_snake!(base, "app name")

    if base == @old_otp do
      abort("the new name is the same as the current one (#{@old_otp}); nothing to do.")
    end

    %{
      otp: opts[:otp] || base,
      module: opts[:module] || derive_module(base),
      joined: opts[:joined] || String.replace(base, "_", ""),
      kebab: opts[:kebab] || String.replace(base, "_", "-"),
      title: opts[:title] || derive_title(base)
    }
  end

  defp prompt_required_name(opts) do
    suggested = suggested_name_from_cwd()

    cond do
      # Non-interactive: fall back to the folder name (the usual `git clone X && cd X`
      # flow makes it the intended name); abort only if it isn't usable.
      opts[:yes] and suggested != nil ->
        info("Using app name #{inspect(suggested)} (from the current folder).")
        suggested

      opts[:yes] ->
        abort("no app name given. Pass it as an argument, e.g. `elixir #{@self_path} my_app`.")

      true ->
        label =
          if suggested,
            do: "New app name (snake_case) [#{suggested}]: ",
            else: "New app name (snake_case, e.g. my_app): "

        case prompt(label, "") do
          "" -> suggested || abort("no app name entered.")
          name -> name
        end
    end
  end

  # Guess the app name from the current directory (the `git clone … my_app && cd
  # my_app` flow makes the folder the intended name). Splits camelCase boundaries,
  # lowercases, and collapses non-alphanumerics to underscores. Returns nil if the
  # result isn't a valid snake_case name (e.g. starts with a digit), so the caller
  # falls back to a plain prompt.
  defp suggested_name_from_cwd() do
    candidate =
      File.cwd!()
      |> Path.basename()
      |> String.replace(~r/([a-z0-9])([A-Z])/, "\\1_\\2")
      |> String.downcase()
      |> String.replace(~r/[^a-z0-9]+/, "_")
      |> String.trim("_")

    cond do
      candidate == "" -> nil
      candidate == @old_otp -> nil
      candidate =~ ~r/^[a-z][a-z0-9_]*$/ -> candidate
      true -> nil
    end
  end

  defp derive_module(snake) do
    snake |> String.split("_", trim: true) |> Enum.map_join(&capitalize/1)
  end

  defp derive_title(snake) do
    snake |> String.split("_", trim: true) |> Enum.map_join(" ", &capitalize/1)
  end

  # Capitalize the first letter only; preserve the rest (so "api" -> "Api", which the
  # user can override to "API" at the confirm step).
  defp capitalize(<<first::utf8, rest::binary>>), do: String.upcase(<<first::utf8>>) <> rest
  defp capitalize(""), do: ""

  # --- Interactive confirmation --------------------------------------------------

  defp confirm_names!(names, opts) do
    names =
      if opts[:yes] do
        names
      else
        info("\nReview the derived names (press Enter to accept, or type a replacement):\n")

        %{
          module: ask_override("Module (PascalCase)", names.module),
          otp: ask_override("OTP app (snake_case)", names.otp),
          joined: ask_override("Joined (lowercase)", names.joined),
          kebab: ask_override("Kebab-case", names.kebab),
          title: ask_override("Display title", names.title)
        }
      end

    validate_names!(names)

    info("""

    Renaming:
      #{@old_module}  ->  #{names.module}
      #{@old_otp}  ->  #{names.otp}
      #{@old_joined}  ->  #{names.joined}
      #{@old_kebab}  ->  #{names.kebab}
    """)

    unless opts[:yes] or opts[:dry_run] do
      case prompt("Proceed? [y/N]: ", "n") |> String.downcase() do
        y when y in ["y", "yes"] -> :ok
        _ -> abort("aborted by user.")
      end
    end

    names
  end

  defp ask_override(label, default) do
    case prompt("  #{label} [#{default}]: ", "") do
      "" -> default
      value -> String.trim(value)
    end
  end

  defp validate_names!(names) do
    validate_module!(names.module)
    validate_snake!(names.otp, "OTP app")
    validate_pattern!(names.joined, ~r/^[a-z][a-z0-9]*$/, "joined name", "lowercase letters/digits")
    validate_pattern!(names.kebab, ~r/^[a-z][a-z0-9-]*$/, "kebab name", "lowercase letters/digits/hyphens")
    if String.trim(names.title) == "", do: abort("display title cannot be empty.")
  end

  defp validate_snake!(value, what) do
    validate_pattern!(value, ~r/^[a-z][a-z0-9_]*$/, what, "lowercase letters, digits, and underscores; must start with a letter")
  end

  defp validate_module!(value) do
    validate_pattern!(value, ~r/^[A-Z][A-Za-z0-9]*$/, "module name", "a PascalCase alias like MyApp")
  end

  defp validate_pattern!(value, regex, what, hint) do
    unless is_binary(value) and value =~ regex do
      abort("invalid #{what}: #{inspect(value)} — expected #{hint}.")
    end
  end

  # --- File discovery ------------------------------------------------------------

  defp collect_text_files() do
    walk(".")
    |> Enum.reject(&(normalize(&1) == @self_path))
    |> Enum.filter(&text_file?/1)
  end

  # Recursive walk that prunes excluded directories. Returns file paths only.
  defp walk(dir) do
    dir
    |> File.ls!()
    |> Enum.flat_map(fn entry ->
      path = Path.join(dir, entry)
      rel = normalize(path)

      cond do
        excluded_dir?(rel) -> []
        File.dir?(path) -> walk(path)
        true -> [path]
      end
    end)
  end

  defp excluded_dir?(rel), do: rel in @excluded_dirs

  # A file is editable text if its bytes are valid UTF-8 with no NUL — this skips
  # binaries (images, fonts, archives) without an extension allowlist to maintain.
  defp text_file?(path) do
    case File.read(path) do
      {:ok, bin} -> String.valid?(bin) and not String.contains?(bin, <<0>>)
      _ -> false
    end
  end

  # --- Content edits -------------------------------------------------------------

  defp plan_content_edits(files, names) do
    files
    |> Enum.reject(&(normalize(&1) == @readme))
    |> Enum.map(fn path -> {path, File.read!(path)} end)
    |> Enum.map(fn {path, content} -> {path, content, replace_tokens(content, names)} end)
    |> Enum.filter(fn {_path, before, after_} -> before != after_ end)
  end

  # Order: Module (Pascal) and Title (has a space) first, then the lowercase forms.
  # The five forms are case/separator-distinct, so the replacements don't interfere.
  defp replace_tokens(content, names) do
    content
    |> String.replace(@old_module, names.module)
    |> String.replace(@old_title, names.title)
    |> String.replace(@old_otp, names.otp)
    |> String.replace(@old_joined, names.joined)
    |> String.replace(@old_kebab, names.kebab)
  end

  defp apply_edits(edits) do
    Enum.each(edits, fn {path, _before, after_} -> File.write!(path, after_) end)
  end

  # --- Path moves ----------------------------------------------------------------

  defp plan_path_moves(names) do
    walk_all_paths(".")
    |> Enum.filter(&name_has_token?/1)
    # Deepest first: rename children before their parent directories so no queued
    # path is invalidated by an earlier rename.
    |> Enum.sort_by(&(-segment_count(&1)))
    |> Enum.map(fn path -> {path, rename_basename(path, names)} end)
  end

  # Like walk/1 but returns directories as well as files (both can need renaming).
  defp walk_all_paths(dir) do
    dir
    |> File.ls!()
    |> Enum.flat_map(fn entry ->
      path = Path.join(dir, entry)
      rel = normalize(path)

      cond do
        excluded_dir?(rel) -> []
        File.dir?(path) -> [path | walk_all_paths(path)]
        true -> [path]
      end
    end)
  end

  defp name_has_token?(path) do
    base = Path.basename(path)
    String.contains?(base, @old_otp) or String.contains?(base, @old_joined) or
      String.contains?(base, @old_kebab) or String.contains?(base, @old_module)
  end

  defp rename_basename(path, names) do
    new_base = path |> Path.basename() |> replace_tokens(names)
    Path.join(Path.dirname(path), new_base)
  end

  defp apply_moves(moves) do
    Enum.each(moves, fn {from, to} ->
      if File.exists?(to) do
        abort("cannot move #{normalize(from)} -> #{normalize(to)}: target already exists.")
      end

      File.rename!(from, to)
    end)
  end

  defp segment_count(path), do: path |> normalize() |> Path.split() |> length()

  # --- README --------------------------------------------------------------------

  defp write_readme(names) do
    File.write!(@readme, readme_template(names))
  end

  defp readme_template(names) do
    """
    # #{names.title}

    A starter application built on **Ash + Phoenix + React**, generated from a boilerplate.

    ## What's included

    - **Authentication** — invite-only magic-link sign-in (Ash Authentication), user roles,
      activation/deactivation, and per-user API keys.
    - **Admin area** — manage users and application settings.
    - **Audit log** — append-only access log scaffolding (opt resources in as you add them).
    - **Agent memory over MCP** — a durable memory store AI assistants can read/write over the
      Model Context Protocol, with local in-BEAM embeddings for semantic search.
    - **Typed RPC** — Ash actions exposed to the frontend with generated TypeScript types.
    - **Frontend** — a Vite-built React SPA using TanStack Router and Query.

    ## Prerequisites

    - Elixir / Erlang and Node — versions are pinned in `mise.toml` (`mise install`).
    - PostgreSQL — a local instance is provided via `docker compose up -d`.

    ## Getting started

    ```sh
    mix setup                      # install deps, set up the DB, build assets, seed an admin
    iex -S mix phx.server          # start the server (http://localhost:4000)
    ```

    The seed creates an admin user (override with `ADMIN_EMAIL` / `ADMIN_NAME`).

    ## Testing

    ```sh
    mix test                       # backend
    cd assets && npm test          # frontend (vitest)
    mix precommit                  # full gate: compile, format, codegen check, tsc, tests
    ```

    ## Project notes

    - `#{names.module}` is the application module; `:#{names.otp}` is the OTP app name.
    - See `AGENTS.md` and `CLAUDE.md` for conventions and AI-agent guidance.
    """
  end

  # --- Reporting -----------------------------------------------------------------

  defp report_dry_run(edits, moves) do
    info("DRY RUN — no files were changed.\n")
    info("Content edits (#{length(edits)} files):")

    edits
    |> Enum.sort_by(fn {path, _, _} -> normalize(path) end)
    |> Enum.each(fn {path, before, _after} ->
      info("  #{normalize(path)}  (#{count_changes(before)} replacements)")
    end)

    info("\nPath moves (#{length(moves)}):")
    Enum.each(moves, fn {from, to} -> info("  #{normalize(from)}  ->  #{normalize(to)}") end)

    info("\nREADME.md would be regenerated.")
  end

  defp report_done(edits, moves, names) do
    info("""

    Done. Renamed to #{names.module} (:#{names.otp}).
      - #{length(edits)} files edited
      - #{length(moves)} paths moved
      - README.md regenerated

    Next steps:
      git status                         # review the rename
      mix deps.get
      mix deps.unlock --unused
      mix ash.codegen --check            # or regenerate: mix ash_typescript.codegen
      (cd assets && npm install)
      mix ecto.reset                     # and: MIX_ENV=test mix ecto.reset
      mix test  &&  (cd assets && npm test)
      rm #{@self_path}                   # one-shot script; delete when done
    """)
  end

  # Rough replacement count for the dry-run report (sum of token occurrences).
  defp count_changes(before) do
    Enum.sum(
      for tok <- [@old_module, @old_otp, @old_joined, @old_kebab, @old_title] do
        max(length(String.split(before, tok)) - 1, 0)
      end
    )
  end

  # --- Small helpers -------------------------------------------------------------

  defp normalize(path), do: path |> Path.relative_to_cwd() |> to_string()

  defp prompt(label, default) do
    case IO.gets(label) do
      :eof -> default
      {:error, _} -> default
      input -> String.trim_trailing(input, "\n")
    end
  end

  defp info(msg), do: IO.puts(msg)

  defp print_help_and_halt() do
    info("""
    Usage: elixir #{@self_path} [NAME] [options]

      NAME                snake_case app name (e.g. my_app). If omitted, defaults to
                          the current folder name (prompted, or used as-is with --yes).

    Options:
      --module NAME       override the derived PascalCase module (e.g. MyApp)
      --otp NAME          override the derived OTP app / snake name
      --joined NAME       override the derived joined lowercase name
      --kebab NAME        override the derived kebab-case name
      --title TEXT        override the derived display title
      --yes               accept derived defaults; no prompts (for CI/non-interactive)
      --dry-run           show what would change without writing anything
      --help              show this help

    Examples:
      elixir #{@self_path} my_app
      elixir #{@self_path} api_gateway --module APIGateway
      elixir #{@self_path} my_app --yes --dry-run
    """)

    System.halt(0)
  end

  defp abort(msg) do
    IO.puts(:stderr, "error: #{msg}")
    System.halt(1)
  end
end

Bootstrap.main(System.argv())
